// Localized function names, as Excel shows them in each language: English name -> local name.
// Only names that differ are listed; anything absent is shown and typed in English. Adding a
// language is adding a table here (plus its separators in regional.ts).

const table = (src: string): Record<string, string> => {
  const out: Record<string, string> = {};
  for (const pair of src.trim().split(/\s+/)) {
    const [en, local] = pair.split("=");
    if (en && local && en !== local) out[en] = local;
  }
  return out;
};

